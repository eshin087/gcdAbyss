/** Merge the static meshes hung directly on each joint that share a material AND an owner (one
 *  gear slot, or the body: userData.slot) into one mesh (their own transforms baked in). Meshes of
 *  different slots never merge, so each slot's meshes can be found and replaced on their own
 *  (rig.slots). `keep` = meshes that must stay separate (toggled ones). */
function mergeStatic(root, keep) {
  const joints = [];
  root.traverse((o) => {
    if (!o.isMesh) joints.push(o);
  });
  for (const j of joints) {
    const groups = new Map(); // material → (slot → meshes)
    for (const c of j.children) {
      if (!c.isMesh || keep.has(c)) continue;
      const bySlot = groups.get(c.material) ?? new Map();
      const slot = c.userData.slot ?? null;
      const list = bySlot.get(slot) ?? [];
      list.push(c);
      bySlot.set(slot, list);
      groups.set(c.material, bySlot);
    }
    for (const [mat, bySlot] of groups) {
      for (const [slot, list] of bySlot) {
        if (list.length < 2) continue;
        const geos = list.map((m) => {
          m.updateMatrix();
          return m.geometry.clone().applyMatrix4(m.matrix);
        });
        for (const m of list) j.remove(m);
        const merged = new THREE.Mesh(mergeGeometries(geos), mat);
        if (slot) merged.userData.slot = slot;
        j.add(merged);
      }
    }
  }
}

/**
 * Build the hero: the skeleton and the body, then the gear in `loadout` (slot → item id, see
 * gear/index.js; default: the Wanderer's set). An empty `chest`, `arms` or `legs` slot gets the
 * plain undersuit (gear/base.js); any other slot may be empty. Returns the rig the animator and the
 * player drive: the joints, `coat` (the skirt panels on springs; [] without a `waist` item),
 * `streamers` (the cape's springs; [] without a `back` item), `gem` and `flask` (always there),
 * the materials, plus
 *   loadout  slot → the id of the item built there (null: empty), every slot listed
 *   slots    slot → the Object3Ds that slot hung on the skeleton (each with its whole subtree, all
 *            tagged userData.slot), so a slot can be emptied and rebuilt without touching the rest
 */
export function buildHero(U, loadout = DEFAULT_LOADOUT) {
  const M = createHeroMaterials(U);

  // joint / mesh helpers for one owner: a gear slot, or null for the skeleton and the body
  const helpers = (slot) => ({
    joint(parent, x = 0, y = 0, z = 0) {
      const j = new THREE.Object3D();
      j.position.set(x, y, z);
      j.rotation.order = 'YXZ';
      if (slot) j.userData.slot = slot;
      parent.add(j);
      return j;
    },
    mesh(parent, geo, mat, x = 0, y = 0, z = 0) {
      if (!geo.attributes.aPart) sub(geo, 0);
      const m = new THREE.Mesh(geo, mat);
      m.position.set(x, y, z);
      if (slot) m.userData.slot = slot;
      parent.add(m);
      return m;
    },
  });
  const { joint, mesh } = helpers(null);

  // ---------------------------------------------------------------- skeleton
  // every joint the animator drives, whatever he wears: gear only hangs meshes (and its own cloth
  // joints) on these
  const root = new THREE.Group();
  root.name = 'player';
  const body = joint(root, 0, DIM.pivot, 0);
  const pelvis = joint(body, ...DIM.pelvis);
  const spine = joint(pelvis, ...DIM.spine);
  const chest = joint(spine, ...DIM.chest);
  // the shoulder-armour joint over the RIGHT shoulder: it follows the right arm part of the way
  // (anim.js PAULDRON_FOLLOW)
  const pauldron = joint(chest, -DIM.shoulder[0], DIM.shoulder[1], DIM.shoulder[2]);
  const head = joint(chest, ...DIM.neck);
  head.scale.setScalar(BODY.headScale);
  const hair = {};
  for (const c of HAIR_CLUSTERS) hair[c.name] = joint(head, ...c.pivot);
  const arms = {};
  for (const side of [-1, 1]) {
    const upper = joint(chest, side * DIM.shoulder[0], DIM.shoulder[1], DIM.shoulder[2]);
    const fore = joint(upper, 0, -DIM.upperArm, 0);
    arms[side < 0 ? 'R' : 'L'] = { upper, fore };
  }
  // the sword hand's targets stay offsets from the round-2 shoulder (DIM.gripShoulder)
  arms.R.anchor = new THREE.Vector3(-DIM.gripShoulder[0], DIM.gripShoulder[1], DIM.gripShoulder[2]);
  const legs = {};
  for (const side of [-1, 1]) {
    const thigh = joint(pelvis, side * DIM.hip[0], DIM.hip[1], DIM.hip[2]);
    const shin = joint(thigh, 0, -DIM.thigh, 0);
    const foot = joint(shin, 0, -DIM.shin, 0);
    legs[side < 0 ? 'R' : 'L'] = { thigh, shin, foot };
  }
  // the weapon joint: posed directly in body space (anim.js); origin = grip centre, blade along +Z
  const sword = joint(body);

  // ---------------------------------------------------------------- body: head and hair
  // a head item may keep only part of the hair under it: `hair` = the pieces to build ('cap' and
  // HAIR_CLUSTERS names; the hood keeps the cap and the fringe), `hidesHair` = none of it (a
  // closed helm). The hair joints stay either way (the animator springs them)
  const worn = resolveLoadout(loadout);
  const headItem = worn.find(({ slot }) => slot === 'head')?.item;
  const hairKeep = headItem?.hidesHair ? new Set() : Array.isArray(headItem?.hair) ? new Set(headItem.hair) : null;
  const hairOn = (name) => !hairKeep || hairKeep.has(name);
  // a deep hood can put the face in shadow (`shadowsFace`): the face takes the near-black of the
  // shirt and the eyes are left out (at the game camera the ASCII never resolves a face; a pale one
  // under gold hair read as a gold mask)
  const shade = !!headItem?.shadowsFace;
  const faceMat = shade ? M.shirt : M.skin;
  {
    const [sx, sy, sz] = DIM.skull;
    mesh(head, limb({ length: 0.12, r0: BODY.neck[0], r1: BODY.neck[1], radial: 8, rings: 2, capSegs: 1 }), faceMat, 0, 0.1, 0.0);
    mesh(head, orient.up(ellipsoidGeometry(0.078, 0.09, 0.1)), faceMat, sx, sy, sz);
    // slim V-jaw with a pointed chin (chin at ~1.57 m)
    const jaw = ellipsoidGeometry(0.05, 0.04, 0.056, { widthSegs: 10, heightSegs: 6 });
    const jp = jaw.attributes.position;
    for (let i = 0; i < jp.count; i++) {
      const z = jp.getZ(i), y = jp.getY(i);
      const k = 1 - 0.45 * Math.max(0, z / 0.056) * Math.max(0, -y / 0.04 + 0.3);
      jp.setX(i, jp.getX(i) * k);
    }
    jaw.computeVertexNormals();
    mesh(head, jaw, faceMat, sx, sy - 0.066, sz + 0.016);
    // the right ear shows below the swept-back locks
    mesh(head, ellipsoidGeometry(0.012, 0.024, 0.018, { widthSegs: 6, heightSegs: 4 }), faceMat, sx - 0.08, sy - 0.014, sz - 0.008);
    // the eyes: half-lidded almonds (smaller since Session 14: two large dark holes in a pale face
    // under the hood read as a skull's sockets)
    if (!shade) for (const ex of [0.032, -0.032]) mesh(head, ellipsoidGeometry(0.014, 0.0065, 0.005, { widthSegs: 8, heightSegs: 4 }), M.eye, sx + ex, sy - 0.012, sz + 0.09);
    if (hairOn('cap')) mesh(head, partGeometry('hair.cap'), M.hair);
  }
  for (const c of HAIR_CLUSTERS) {
    if (!hairOn(c.name)) continue;
    const j = hair[c.name];
    mesh(j, partGeometry(`hair.${c.name}.mass`), M.hair);
    mesh(j, partGeometry(`hair.${c.name}.tip`), M.hairTip);
  }

  // ---------------------------------------------------------------- gear
  // each equipped item hangs its meshes on the skeleton (gear/README.md: the item contract) and
  // may hand back the handles the animator needs
  const skeleton = { root, body, pelvis, spine, chest, head, arms, legs, pauldron, sword };
  const handles = { coat: [], streamers: [], keep: [], gem: null, flask: null, offHand: null };
  const equipped = {};
  for (const { slot, item } of worn) {
    equipped[slot] = item ? item.id : null;
    if (!item) continue;
    const h = item.build({ ...skeleton, M, DIM, BODY, REST, slot, item, ...helpers(slot) });
    if (h?.coat) handles.coat.push(...h.coat);
    if (h?.streamers) handles.streamers.push(...h.streamers);
    if (h?.keep) handles.keep.push(...h.keep);
    if (h?.gem) handles.gem = h.gem;
    if (h?.flask) handles.flask = h.flask;
    if (h?.offHand) handles.offHand = h.offHand;
  }
  // what an empty slot leaves the animator and the player (they read these every frame): no coat
  // panels, no streamers, the gem's marker joint at its usual spot on the weapon joint (its glow
  // sprite and glints, player.js), and the body's own flask
  const { coat, streamers } = handles;
  const gem = handles.gem ?? joint(sword, 0, 0, DIM.gem);
  // flask, shown only while healing
  const flask = handles.flask ?? mesh(arms.L.fore, orient.up(ellipsoidGeometry(0.036, 0.036, 0.055, { widthSegs: 10, heightSegs: 6 })), M.flask, 0, -DIM.foreArm - 0.03, 0.068);
  flask.visible = false;

  // fewer draw calls: static meshes sharing a joint, a material and an owner become one mesh
  mergeStatic(root, new Set([flask, ...handles.keep]));

  // who owns what: the objects each slot hung on the skeleton (after the merge)
  const slots = Object.fromEntries(SLOTS.map((s) => [s, []]));
  root.traverse((o) => {
    const s = o.userData.slot;
    if (s && o.parent?.userData.slot !== s) slots[s]?.push(o);
  });

  const mats = Object.values(M);
  return {
    root, body, pelvis, spine, chest, head, hair, arms, legs, coat, streamers, sword, gem, pauldron, flask,
    // { open, grip } | null: the free hand hanging open, and the same hand closed on the grip below
    // the sword hand; the animator shows one or the other with `twoHand` (gear/README.md)
    offHand: handles.offHand,
    loadout: equipped,
    slots,
    materials: M,
    mats,
    // joints sampled for body-attached FX (burn flames, Ghostep afterimage)
    fxPoints: [chest, chest, pelvis, head, arms.R.upper, arms.L.upper, legs.R.thigh, legs.L.thigh, legs.R.shin, legs.L.shin],
    // afterimage outline: joint chains whose segments are traced with glyphs
    ghostChains: [
      [head, chest, spine, pelvis],
      [arms.R.upper, arms.R.fore],
      [arms.L.upper, arms.L.fore],
      [legs.R.thigh, legs.R.shin, legs.R.foot],
      [legs.L.thigh, legs.L.shin, legs.L.foot],
    ],
  };
}
